import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { basename, resolve } from 'node:path';
import { spawnSync } from 'node:child_process';
import { mediaInputPath } from './media-input.mjs';

const hash = (bytes) => createHash('sha256').update(bytes).digest('hex');
function run(args) {
  const process = spawnSync('ffmpeg', ['-v', 'error', '-y', ...args], { encoding: 'utf8' });
  if (process.error || process.status !== 0) throw process.error ?? Error(process.stderr);
}

export async function prepareArchiveVideos(media) {
  const version = spawnSync('ffmpeg', ['-version'], { encoding: 'utf8' });
  const records = {};
  for (const row of media.filter((row) => row.kind === 'video' && row.archiveSource?.inputPath)) {
    // Local originals stay outside public; legacy /video/... inputs remain supported.
    const input = mediaInputPath(row, row.archiveSource.inputPath);
    const sourceSha256 = hash(await readFile(input));
    if (sourceSha256 !== row.archiveSource.sha256) throw Error(`Video source changed: ${row.id}`);
    const segment = row.archiveSource.segment;
    if (
      segment &&
      (!Number.isFinite(segment.start) ||
        segment.start < 0 ||
        !Number.isFinite(segment.duration) ||
        segment.duration <= 0)
    )
      throw Error(`Invalid video segment: ${row.id}`);
    const seek = segment ? ['-ss', String(segment.start)] : [];
    const duration = segment ? ['-t', String(segment.duration)] : [];
    const key = hash(
      Buffer.from(
        JSON.stringify({
          sourceSha256,
          version: version.stdout.split('\n')[0],
          policy: {
            version: 2,
            segment,
            audio: 'aac-96k',
            codec: 'libx264',
            pixelFormat: 'yuv420p',
            crf: 28,
            previewCrf: 30,
            previewSeconds: 8,
            previewWidth: 640,
          },
        }),
      ),
    );
    const cache = resolve('.local-server/media-cache', 'video-' + key);
    await mkdir(cache, { recursive: true });
    const files = [row.src, row.previewSrc, row.poster];
    const manifestPath = resolve(cache, 'manifest.json');
    let manifest;
    try {
      manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
      if (
        manifest.sourceSha256 !== sourceSha256 ||
        manifest.policyVersion !== 2 ||
        manifest.segment?.start !== segment?.start ||
        manifest.segment?.duration !== segment?.duration ||
        manifest.files?.length !== files.length ||
        manifest.files.some((file) => !files.includes(file.src))
      )
        throw Error('Invalid video cache record');
      for (const file of manifest.files)
        if (hash(await readFile(resolve(cache, basename(file.src)))) !== file.sha256)
          throw Error('Video cache changed');
    } catch {
      manifest = undefined;
    }
    if (!manifest) {
      run([
        ...seek,
        '-i',
        input,
        ...duration,
        '-map',
        '0:v:0',
        '-map',
        '0:a?',
        '-c:a',
        'aac',
        '-b:a',
        '96k',
        '-c:v',
        'libx264',
        '-crf',
        '28',
        '-pix_fmt',
        'yuv420p',
        '-movflags',
        '+faststart',
        resolve(cache, basename(row.src)),
      ]);
      run([
        ...seek,
        '-i',
        input,
        '-t',
        String(Math.min(8, segment?.duration ?? 8)),
        '-an',
        '-vf',
        "scale='min(640,iw)':-2",
        '-c:v',
        'libx264',
        '-crf',
        '30',
        '-pix_fmt',
        'yuv420p',
        '-movflags',
        '+faststart',
        resolve(cache, basename(row.previewSrc)),
      ]);
      run([
        ...seek,
        '-i',
        input,
        '-frames:v',
        '1',
        '-c:v',
        'libwebp',
        '-quality',
        '85',
        resolve(cache, basename(row.poster)),
      ]);
      manifest = {
        sourceSha256,
        policyVersion: 2,
        ...(segment ? { segment } : {}),
        files: await Promise.all(
          files.map(async (src) => {
            const bytes = await readFile(resolve(cache, basename(src)));
            return { src, sha256: hash(bytes), bytes: bytes.length };
          }),
        ),
      };
      await writeFile(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
    }
    for (const file of manifest.files) {
      const destination = resolve('public', file.src.slice(1));
      const existing = await readFile(destination).catch(() => undefined);
      if (!existing || hash(existing) !== file.sha256) {
        await mkdir(resolve(destination, '..'), { recursive: true });
        await writeFile(destination, await readFile(resolve(cache, basename(file.src))));
      }
    }
    records[row.id] = manifest;
    console.log(`${row.id}: full video, eight-second preview and first-frame poster prepared`);
  }
  await writeFile(
    'src/data/prepared-videos.ts',
    '// Generated by media:prepare; original fingerprints stay out of the public projection.\n' +
      'export const preparedVideos = ' +
      JSON.stringify(records, null, 2) +
      ';\n',
  );
}
